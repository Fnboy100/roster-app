/**
 * exportInventoryReportPDF.js
 * Client-side PDF export for the Inventory > Reports page, mirroring the
 * roster's exportPDF.js pattern (same jsPDF + jspdf-autotable already used
 * there — no new dependency needed).
 *
 * Every PDF is stamped with who generated it and when, both in the header
 * and repeated in the footer of every page. The department (or "All
 * Departments" for an unscoped report) is always rendered as its own
 * bold line — not folded into the smaller filters text — so every
 * exported report, from every part of this app, leads with the same
 * bold department identification.
 */

import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

const ACCENT_RGB = [217, 164, 65]; // #D9A441 — matches the reporting accent color used for roster/presence PDF exports

/**
 * @param {string} title - report title, e.g. "Stock Movement Totals"
 * @param {string[]} columns - table header labels
 * @param {(string|number)[][]} rows - table body rows
 * @param {string} generatedBy - display name/email of the user exporting the report
 * @param {string} [department] - department name, or omit/pass "" for an unscoped/all-departments report — always rendered boldly, separate from filtersLabel
 * @param {string} [filtersLabel] - human-readable summary of other active filters (date range, etc — department no longer needs to be folded in here)
 */
export function exportReportPDF({ title, columns, rows, generatedBy, department, filtersLabel }) {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const now = new Date();
  const generatedOn = now.toLocaleString('en-US', { dateStyle: 'long', timeStyle: 'short' });

  // ── Department — bold and first, always ──────────────────────────────
  const deptLabel = (department || 'All Departments').toUpperCase();
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(15, 23, 42);
  doc.text(deptLabel, 40, 40);

  const accentBarY = 48;
  doc.setFillColor(...ACCENT_RGB);
  doc.rect(40, accentBarY, 130, 3, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(71, 85, 105);
  doc.text(title, 40, 68);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(100, 116, 139);
  doc.text(`Generated by: ${generatedBy}`, 40, 84);
  doc.text(`Generated on: ${generatedOn}`, 40, 97);
  let startY = 111;
  if (filtersLabel) {
    const filterLines = doc.splitTextToSize(filtersLabel, pageWidth - 80);
    doc.text(filterLines, 40, 111);
    startY = 111 + filterLines.length * 11 + 8;
  }

  autoTable(doc, {
    head: [columns],
    body: rows,
    startY,
    margin: { left: 40, right: 40 },
    theme: 'grid',
    styles: {
      fontSize: 9,
      cellPadding: 6,
      lineColor: [226, 232, 240],
      lineWidth: 0.5,
      overflow: 'linebreak',
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
  });

  // Stamp every page's footer, not just the first — so the provenance
  // (who/when/which department) survives even if the table spans
  // multiple pages.
  const pageCount = doc.internal.getNumberOfPages();
  const pageHeight = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(deptLabel, 40, pageHeight - 20);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.text(`Generated by ${generatedBy} on ${generatedOn}`, 130, pageHeight - 20);
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 80, pageHeight - 20);
  }

  const stamp = now.toISOString().slice(0, 10);
  const safeTitle = title.replace(/\s+/g, '_').toLowerCase();
  const safeDept = deptLabel.replace(/\s+/g, '_').toLowerCase();
  doc.save(`${safeDept}_${safeTitle}_${stamp}.pdf`);
}
